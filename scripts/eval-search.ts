// Evaluates the "Ask my work" search box the way BookMind is evaluated: a gold set, a refusal
// bar tuned on one split, and results reported on a split the tuning never saw.
// Writes src/data/search-eval.json, which the site displays and the browser reads its bar from.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Bm25, decide, type RefusalParams } from '../src/lib/bm25.ts';
import { buildCorpus, indexText } from '../src/lib/corpus.ts';
import { aboutPassages } from '../src/lib/about.ts';
import { ROOT, loadProjects } from '../src/lib/load-projects.ts';

interface Gold {
  q: string;
  split: 'dev' | 'test';
  expect: string[] | null;
}

const entries = loadProjects();
const corpus = buildCorpus(entries, aboutPassages);
const index = new Bm25(corpus.map((p) => ({ id: p.id, text: indexText(p) })));
const projectOf = new Map(corpus.map((p) => [p.id, p.project]));
const gold: Gold[] = JSON.parse(readFileSync(join(ROOT, 'src', 'data', 'search-gold.json'), 'utf8')).questions;

const known = new Set([...entries.map((e) => e.id), 'about']);
for (const g of gold) for (const id of g.expect ?? []) if (!known.has(id)) throw new Error(`gold question "${g.q}" expects unknown project "${id}"`);

interface Row {
  hit: boolean;
  rank: number | null;
  refused: boolean;
}
function run(g: Gold, params: RefusalParams): Row {
  const hits = index.search(g.q, 5);
  const decision = decide(g.q, hits, params);
  const projects = hits.slice(0, 3).map((h) => projectOf.get(h.id)!);
  const rankIdx = g.expect ? hits.map((h) => projectOf.get(h.id)!).findIndex((p) => g.expect!.includes(p)) : -1;
  return { hit: g.expect ? projects.some((p) => g.expect!.includes(p)) : false, rank: rankIdx >= 0 ? rankIdx + 1 : null, refused: decision.refused };
}

function score(split: 'dev' | 'test', params: RefusalParams) {
  const qs = gold.filter((g) => g.split === split);
  let correct = 0;
  let falseRefusals = 0;
  let falseAnswers = 0;
  let answerableHits = 0;
  let rr = 0;
  const answerable = qs.filter((g) => g.expect);
  const offTopic = qs.filter((g) => !g.expect);
  for (const g of qs) {
    const r = run(g, params);
    if (g.expect) {
      if (r.hit && !r.refused) correct += 1;
      if (r.refused) falseRefusals += 1;
      if (r.hit) answerableHits += 1;
      if (r.rank) rr += 1 / r.rank;
    } else {
      if (r.refused) correct += 1;
      else falseAnswers += 1;
    }
  }
  return {
    n: qs.length,
    nAnswerable: answerable.length,
    nOffTopic: offTopic.length,
    correct,
    hitAt3: answerableHits,
    mrr: answerable.length ? Number((rr / answerable.length).toFixed(3)) : 0,
    falseRefusals,
    offTopicRefused: offTopic.length - falseAnswers,
    falseAnswers,
  };
}

// Tune the refusal bar on dev only.
const knowns = [0, 0.34, 0.5, 0.6, 0.67, 0.75];
const coverages = [0, 0.25, 0.34, 0.5, 0.6, 0.75];
const minScores = [0, 1, 2, 3, 4, 5, 6, 8];
let best: { params: RefusalParams; s: ReturnType<typeof score> } | null = null;
for (const minKnown of knowns) {
  for (const minCoverage of coverages) {
    for (const minScore of minScores) {
      const params = { minKnown, minCoverage, minScore };
      const s = score('dev', params);
      // Most correct wins; then fewest wrongly refused questions (a refused recruiter is worse than
      // an extra passage); then the strictest bars, so near-ties lean toward refusing.
      const strict = minKnown + minCoverage + minScore / 10;
      const bestStrict = best ? best.params.minKnown + best.params.minCoverage + best.params.minScore / 10 : -1;
      const better =
        !best ||
        s.correct > best.s.correct ||
        (s.correct === best.s.correct && s.falseRefusals < best.s.falseRefusals) ||
        (s.correct === best.s.correct && s.falseRefusals === best.s.falseRefusals && strict > bestStrict);
      if (better) best = { params, s };
    }
  }
}
const params = best!.params;
if (process.argv.includes('--verbose')) {
  // Dev questions only: the test split is never inspected question by question.
  for (const g of gold.filter((x) => x.split === 'dev')) {
    const hits = index.search(g.q, 3);
    const d = decide(g.q, hits, params);
    const ok = g.expect ? !d.refused && hits.some((h) => g.expect!.includes(projectOf.get(h.id)!)) : d.refused;
    if (!ok) console.log(`  dev miss: ${JSON.stringify(g.q)} -> ${d.refused ? 'REFUSED' : 'answered ' + hits.map((h) => h.id).join(', ')} (${d.reason})`);
  }
}
const dev = score('dev', params);
const test = score('test', params);

const out = {
  _about: 'Generated by scripts/eval-search.ts from src/data/search-gold.json. Do not edit by hand.',
  params,
  passages: corpus.length,
  dev: { n: dev.n, correct: dev.correct },
  test: {
    n: test.n,
    answerable: test.nAnswerable,
    offTopic: test.nOffTopic,
    correct: test.correct,
    hitAt3: test.hitAt3,
    mrr: test.mrr,
    falseRefusals: test.falseRefusals,
    offTopicRefused: test.offTopicRefused,
    falseAnswers: test.falseAnswers,
  },
};
writeFileSync(join(ROOT, 'src', 'data', 'search-eval.json'), JSON.stringify(out, null, 2) + '\n');

console.log(`Search eval  (${corpus.length} passages, refusal bar tuned on ${dev.n} dev questions)`);
console.log(`  bar: known-term share >= ${params.minKnown}, weighted coverage >= ${params.minCoverage}, top score >= ${params.minScore}`);
console.log(`  dev : ${dev.correct}/${dev.n} correct`);
console.log(`  test: ${test.correct}/${test.n} correct | right project in top 3: ${test.hitAt3}/${test.nAnswerable} (MRR ${test.mrr}) | wrongly refused: ${test.falseRefusals} | off-topic refused: ${test.offTopicRefused}/${test.nOffTopic}`);
